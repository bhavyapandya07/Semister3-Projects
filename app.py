# TAB 1 — User Simulator
# ══════════════════════════════════════════════════════════════════════════════
with tab1:
    col_left, col_right = st.columns([1, 1.6], gap="large")

    with col_left:
        st.markdown('<div class="section-title">Select a Visitor</div>', unsafe_allow_html=True)

        search_mode = st.radio(
            "Input method",
            ["Dropdown (known users)", "Type a Visitor ID"],
            horizontal=True,
            label_visibility="collapsed",
        )

        if search_mode == "Dropdown (known users)":
            selected_user = st.selectbox(
                "Visitor ID",
                options=all_users[:5000],  # cap for perf
                label_visibility="collapsed",
            )
        else:
            selected_user = st.text_input(
                "Enter Visitor ID",
                placeholder="e.g. 1234567",
                label_visibility="collapsed",
            ).strip()

        if selected_user:
            # ── User history ──────────────────────────────────────────────────
            st.markdown('<div class="section-title">Past Activity</div>', unsafe_allow_html=True)
            history = (
                events_df[events_df["visitorid"] == str(selected_user)]
                .sort_values("timestamp", ascending=False)
                .head(10)
            )
            if history.empty:
                st.info("No historical activity found for this visitor in the sampled data.")
            else:
                badge_cls = {
                    "view":        "badge-view",
                    "addtocart":   "badge-addtocart",
                    "transaction": "badge-transaction",
                }
                rows_html = ""
                for _, row in history.iterrows():
                    ev = str(row.get("event", ""))
                    item = str(row.get("itemid", "—"))
                    cls  = badge_cls.get(ev, "badge-view")
                    rows_html += (
                        f'<div class="hist-row">'
                        f'  <span class="badge {cls}">{ev.upper()}</span>'
                        f'  <span style="color:#94a3b8;font-size:.85rem;">Item <b style="color:#e2e8f0">{item}</b></span>'
                        f'</div>'
                    )
                st.markdown(rows_html, unsafe_allow_html=True)

    with col_right:
        if selected_user:
            st.markdown('<div class="section-title">Top 5 Recommendations</div>', unsafe_allow_html=True)

            user_recs = recs_df[recs_df["visitorid"] == str(selected_user)]

            if user_recs.empty:
                st.warning(
                    "🥶 **Cold-Start User** — This visitor wasn't seen during training. "
                    "ALS cannot generate personalised recommendations for unseen users. "
                    "Consider a fallback strategy (e.g. popularity-based recs).",
                    icon="❄️",
                )
            else:
                user_recs = user_recs.sort_values("als_score", ascending=False).head(5)
                max_score = float(user_recs["als_score"].max()) if len(user_recs) else 1.0

                cards_html = ""
                for rank, (_, row) in enumerate(user_recs.iterrows(), 1):
                    score  = float(row["als_score"])
                    item   = str(row["recommended_itemid"])
                    pct    = max(5, int(score / max_score * 100))
                    cards_html += f"""
                    <div class="rec-card">
                      <div class="rec-rank">#{rank}</div>
                      <div class="rec-body">
                        <div class="rec-item">Item {item}</div>
                        <div class="rec-score">ALS confidence score: {score:.4f}</div>
                        <div class="score-bar" style="width:{pct}%;"></div>
                      </div>
                    </div>"""
                st.markdown(cards_html, unsafe_allow_html=True)

                with st.expander("🔍 Raw recommendation data"):
                    st.dataframe(
                        user_recs[["recommended_itemid", "als_score"]].reset_index(drop=True),
                        use_container_width=True,
                    )

        else:
            st.markdown(
                """
                <div style="height:100%;display:flex;align-items:center;justify-content:center;
                            flex-direction:column;gap:.5rem;padding:3rem;text-align:center;">
                  <div style="font-size:3rem;">👈</div>
                  <div style="color:#475569;font-size:.95rem;">
                    Select or enter a Visitor ID on the left<br>to see their personalised recommendations.
                  </div>
                </div>
                """,
                unsafe_allow_html=True,
            )

