# ── Paths ──────────────────────────────────────────────────────────────────────
BASE_DIR    = os.path.dirname(os.path.abspath(__file__))
PARQUET_DIR = os.path.join(BASE_DIR, "output", "recommendations.parquet")
META_PATH   = os.path.join(BASE_DIR, "output", "meta.json")
EVENTS_PATH = os.path.join(BASE_DIR, "events.csv")


# ── Data Loading ───────────────────────────────────────────────────────────────
@st.cache_data(show_spinner=False)
def load_recommendations():
    return pd.read_parquet(PARQUET_DIR)


@st.cache_data(show_spinner=False)
def load_events(nrows=200_000):
    return pd.read_csv(EVENTS_PATH, nrows=nrows)


@st.cache_data(show_spinner=False)
def load_meta():
    if os.path.exists(META_PATH):
        with open(META_PATH) as f:
            return json.load(f)
    return {}


# Check pipeline output
pipeline_ready = os.path.exists(PARQUET_DIR)

# ── Hero Header ────────────────────────────────────────────────────────────────
